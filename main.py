def build_vectorstore(pdf_folder_path="./papers"):
    """
    Membaca seluruh file PDF jurnal/tesis dari folder ./papers
    dan menyimpannya ke dalam Vectorstore FAISS menggunakan Embedding Lokal.
    """
    print("[+] Membaca file PDF jurnal/tesis dari folder:", pdf_folder_path)
    if not os.path.exists(pdf_folder_path):
        os.makedirs(pdf_folder_path)
        print(f"[-] Folder '{pdf_folder_path}' belum ada. Folder telah dibuat, silakan isi dengan file PDF.")
        return None

    loader = PyPDFDirectoryLoader(pdf_folder_path)
    documents = loader.load()

    if len(documents) == 0:
        print("[-] Tidak ada file PDF ditemukan di folder ./papers. Silakan unggah beberapa file PDF terlebih dahulu!")
        return None

    text_splitter = RecursiveCharacterTextSplitter(
        chunk_size=1000,
        chunk_overlap=150
    )
    docs = text_splitter.split_documents(documents)

    print("[+] Memuat model embedding lokal (all-MiniLM-L6-v2)...")
    embeddings = HuggingFaceEmbeddings(model_name="sentence-transformers/all-MiniLM-L6-v2")

    vectorstore = FAISS.from_documents(docs, embeddings)
    print(f"[+] Vectorstore FAISS berhasil dibangun dengan {len(docs)} chunks.")
    return vectorstore

# PROMPT TEMPLATE KHUSUS EKSTRAKSI GAP MATRIX
GAP_MATRIX_PROMPT = """
Anda adalah pakar senior AI di bidang Cyber Security dan Intelligence Systems.
Berdasarkan konteks dokumen ilmiah yang diberikan berikut:
{{context}}

Tugas Anda: Sintesiskan informasi dari artikel-artikel tersebut dan buatkan **Literature GAP Matrix** dalam bentuk tabel Markdown untuk topik: "{{input}}".

Tabel Markdown HARUS memiliki format kolom:
| No | Penulis & Tahun | Judul Penelitian | Metode AI / RAG | Fokus Konten / Domain | Temuan Utama | Research Gap / Keterbatasan |

Aturan Ekstraksi:
1. Analisis secara cermat keterbatasan metode, dataset, dan implementasi operasional.
2. Identifikasi research gap secara spesifik (misal: keterbatasan multimodal, belum adanya integrasi Knowledge Graph lokal, latency streaming data, atau bahasa terselubung/kode).

Jawaban:
"""

def run_gap_matrix_pipeline(vectorstore):
    retriever = vectorstore.as_retriever(search_kwargs={"k": 5})

    print("[+] Menghubungkan ke LLM Lokal Ollama (Llama-3)...")
    llm = ChatOllama(
        model="llama3",
        temperature=0.1
    )

    prompt = PromptTemplate(
        template=GAP_MATRIX_PROMPT,
        input_variables=["context", "input"]
    )

    # Menggunakan representasi chain modern yang direkomendasikan LangChain terbaru
    combine_docs_chain = create_stuff_documents_chain(llm, prompt)
    qa_chain = create_retrieval_chain(retriever, combine_docs_chain)

    query = "Ekstrak ringkasan, metode RAG, temuan utama, dan research gap dari paper patroli siber, deteksi radikalisme, dan ancaman siber."
    print("[+] Memproses RAG Query dengan Llama-3...")
    response = qa_chain.invoke({"input": query})
    return response["answer"]

# Eksekusi Pipeline
vector_db = build_vectorstore("./papers")
if vector_db:
    matrix_result = run_gap_matrix_pipeline(vector_db)

    print("\n=== LITERATURE GAP MATRIX GENERATED BY LLAMA-3 (OLLAMA) ===\n")
    print(matrix_result)

    # Simpan luaran ke file Literature_GAP_Matrix.md
    with open("Literature_GAP_Matrix.md", "w", encoding="utf-8") as f:
        f.write(matrix_result)
    print("\n[+] Hasil GAP Matrix berhasil disimpan ke 'Literature_GAP_Matrix.md'")